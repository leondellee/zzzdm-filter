def main() -> None:
    clf = Classifier()
    fails = []
    for case in CASES:
        title, body, expect_drop, note = case[:4]
        price = case[4] if len(case) > 4 else ""
        expect_cat = case[5] if len(case) > 5 else None
        v = clf.classify(title, body, price)
        bad_drop = v.drop != expect_drop
        bad_cat = bool(expect_cat) and v.category != expect_cat
        if bad_drop or bad_cat:
            fails.append((title, expect_drop, v.drop, v.category, v.matched, note,
                          expect_cat))

    total = len(CASES)
    print(f"回归用例 {total} 条")
    if not fails:
        drops = sum(1 for c in CASES if c[2])
        print(f"全部通过 ✓  （保留 {total - drops} / 剔除 {drops}）")
        return

    print(f"失败 {len(fails)} 条：")
    for t, exp, got, cat, kw, note, exp_cat in fails:
        print(f"  ✗ {t}")
        print(f"      期望 {'剔除' if exp else '保留'}"
              f"{f'（品类应={exp_cat}）' if exp_cat else ''}，"
              f"实际 {'剔除' if got else '保留'}"
              f"{f'（{cat}｜{kw}）' if got else ''}")
        print(f"      说明：{note}")
    sys.exit(1)


if __name__ == "__main__":
    main()

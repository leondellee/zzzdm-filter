#      但本质是开卡活动，应归「开通类」而非「生鲜-肉类」。
# 若不做优先级处理，结果虽同为剔除，但归因错误会干扰后续调规则。
PRIORITY_CATEGORIES = [
    "开通类/虚拟服务",
    # Leon 2026-10-13：宠物用品须先于「生鲜-肉类」判定。
    # 真实样本「ACANA 爱肯拿 无谷鸡肉全阶段猫粮」含"鸡肉"，
    # 会被肉类规则先命中，归因错标成生鲜。
    "宠物用品",
    # 同理：「川娃子 双椒酱」「牛肉酱」含肉字，须先于肉类判定。
    "下饭酱",
    # Leon 2026-10-15：1号会员店是**平台标记**，商品几乎全是生鲜——
    # 若不加优先级，「1号会员店 谷饲牛腩」会被生鲜规则抢先归因。
    "1号会员店",
    # 汽车保养同理：机油品牌「壳牌」含"喜力"等子串问题已由 exclude 处理，
    # 但「美孚1号」的"1号"与 1号会员店无冲突；保持默认顺序即可。
]


# ---------------------------------------------------------------------------
# 零价格帖剔除（Leon 2026-09-19 追加）
# ---------------------------------------------------------------------------
# 现象：价格解析为 0 的帖子，绝大多数不是"值得买"的商品，而是：
#   · 入会/开卡/关注/加购送豆送积分（虚拟活动）
#   · 店铺浮标抽奖、超市卡
#   · 返红包后"实付 0 元"的凑单帖（本质是薅羊毛教程，不是商品推荐）
#
# 实测（158 条样本）：9 条零价格帖中，8 条是纯虚拟活动，1 条是
# 「返3元红包后实际支付0元」的凑单帖——仍属应剔除之列。
# 故零价格一律剔除，不设例外。
# ---------------------------------------------------------------------------
# 括号赠品片段剥离（2026-10-13）
# ---------------------------------------------------------------------------
# 现象：zzzdm 标题常把赠品写进括号，赠品的品类词会污染主商品判定。
#   「红牛 维生素电解质饮料 500ml*15瓶（赠 蒙牛特仑苏纯牛奶250ml*16盒）」
#   → 含"纯牛奶"被牛奶规则剔除，但主商品是电解质饮料（Leon 会漏看它）
# 解法：判定前先剥掉**括号内**含赠/送字样的片段。
# 为什么不剥全部括号：「（130-150斤）」是服装尺码、「（门店有售）」是备注，
# 这些括号不含赠/送，不受影响——只剥赠品，范围最小。
_GIFT_FRAGMENT = re.compile(
    r'[（(【\[][^）)】\]]*(?:赠|送|加赠)[^）)】\]]*[）)】\]]')
# ---------------------------------------------------------------------------
# 关于「按重量单位屏蔽生鲜/水果」——实测否决（Leon 2026-10-13 提议）
# ---------------------------------------------------------------------------
# 提议：生鲜食品、水果多用「斤」「kg」计量，可否按单位直接屏蔽？
#
# 100 条真实样本实测，单位**不是**品类独占信号，反例充分：
#   「雅戈尔 男士夹克 L（130-150斤）」  ← 服装尺码（适合体重）
#   「Erwin Rommel 纯羊毛保暖被子 6斤」 ← 床品填充重量
#   「小天鹅 滚筒洗衣机 12kg」          ← 家电容量
#   「铂钻 膨化土猫砂 10L（送4.2kg）」  ← 宠物耗材
#   「金龙鱼 盘锦大米 5KG*4袋」         ← 粮油（已剔，但单位无区分力）
# 若把「斤/kg」做成独立维度，上述服装/家电/床品会被整片误杀。
#
# 结论：单位只作为**品类词之后的辅助确认**，不构成独立剔除路径。
# 真正能提升召回的是补品类词与品种名（蜜柚、三红柚、走地鸡…），
# 这些已在对应规则里落地。
# ---------------------------------------------------------------------------
_ZERO_PRICE = re.compile(r'^\s*(?:[¥￥])?\s*0+(?:\.0+)?\s*元?\s*$')


def is_zero_price(price: str) -> bool:
    """判断价格字段是否为 0 元。空价格不算（那是没抓到，不是真的 0）。"""
    if not price:
        return False
    return bool(_ZERO_PRICE.match(price))


@dataclass
class Verdict:
    drop: bool
    category: str | None = None
    matched: str | None = None
    kept_by: str | None = None
    reason: str = ""

    def __str__(self) -> str:
        if self.drop:
            return f"剔除[{self.category}] 命中「{self.matched}」"
        if self.kept_by:
            return f"保留（例外保护：{self.kept_by}）"
        return "保留（不在排除清单）"


class Classifier:
    def __init__(self) -> None:
        self._drop = []
        for rule in DROP_RULES:
            kws = sorted(rule["keywords"], key=len, reverse=True)
            self._drop.append({
                "category": rule["category"],
                "keywords": kws,
                "exclude": [self._norm(e) for e in rule.get("exclude", [])],
                "exclude_re": [re.compile(p) for p in rule.get("exclude_re", [])],
                # 独占品牌（Leon 2026-10-13）：该品牌几乎只做这一个品类，
                # 命中品牌名即可剔除，无需品类词同现。见 _check_drop 注释。
                "brands_exclusive": [self._norm(b)
                                     for b in rule.get("brands_exclusive", [])],
            })
        # 高优先级规则前置，保证营销活动类先于商品品类判定
        self._drop.sort(
            key=lambda r: 0 if r["category"] in PRIORITY_CATEGORIES else 1)
        self._keep = list(KEEP_PATTERNS)

    # -- 文本归一 ---------------------------------------------------------
    @staticmethod
    def _norm(text: str) -> str:
        """归一化：去掉各类空白与常见分隔符，统一大小写。

        zzzdm 标题写法不统一，「小米 电视」「小米·电视」「小米电视」都会出现。
        归一化后比对，可让 exclude 列表不被排版差异绕过。
        """
        if not text:
            return ""
        text = text.lower()
        return re.sub(r"[\s\u3000·・\-—_|/\\,.，。、:：;；!！?？~～]+", "", text)

    # -- 例外保护 ---------------------------------------------------------
    def _check_keep(self, title: str, body: str) -> str | None:
        text = self._norm(title + " " + body)
        # 零食语义优先否决："儿童休闲零食"不是婴幼儿用品（Leon 2026-09-19）
        # 仅在出现儿童相关词时才需要这道守卫，否则「零食」会误伤普通商品
        if any(g in text for g in KEEP_SNACK_GUARD):
            if re.search(r"儿童|宝宝|婴幼儿|婴儿|小童|中童|大童", text):
                return None
        # 婴幼儿词泛化守卫：「宝宝洗衣液」「婴幼儿抽纸」「宝宝牛奶」这类
        # 标题里的婴幼儿词只是修饰语，主体是那个通用品类（Leon 已明令剔除）。
        # 不加这道守卫，白名单会把它们整片保下来（Leon 2026-10-13 实测暴露）。
        if any(g in text for g in KEEP_INFANT_CATEGORY_GUARD):
            return None
        # 若命中成人奶粉等守卫词，则 KEEP 中的"奶粉"类失效
        for guard in KEEP_GUARD_EXCLUDE:
            if re.search(guard, text):
                # 只放行非奶粉类例外（服装/用品）
                for pat, name in self._keep:
                    if name == "婴幼儿奶粉":
                        continue
                    if re.search(pat, text):
                        return name
                return None
        for pat, name in self._keep:
            if re.search(pat, text):
                return name
        return None

    # -- 黑名单判定 -------------------------------------------------------
    def _check_drop(self, title: str, body: str) -> tuple[str, str] | None:
        """判定范围以标题为准。

        为什么只看标题：zzzdm 的正文是优惠凑单流水账，包含大量噪声——
        「凑单选了坚果」「赠品是月饼」「也可看看某白酒」等。这些描述的商品
        并不是本条推送的主体。若正文参与判定，会把手机壳、充电器这类
        正常商品整片误杀。标题才是商品本体。

        兜底：标题为空或过短（<4字）时，才退回正文判定，避免空标题漏判。
        """
        # 先剥括号赠品片段，避免赠品品类词污染主商品判定
        title = _GIFT_FRAGMENT.sub("", title or "")
        body = _GIFT_FRAGMENT.sub("", body or "")

        scopes: list[tuple[str, str]] = []
        if len(title) >= 4:
            scopes.append(("标题", self._norm(title)))
        elif body:
            scopes.append(("正文", self._norm(body)))

        for _scope, text in scopes:
            for rule in self._drop:
                # exclude 是文本级免死金牌：命中即整条规则失效
                if any(ex in text for ex in rule["exclude"]):
                    continue
                if any(rx.search(text) for rx in rule["exclude_re"]):
                    continue
                # 独占品牌先于关键词：归因更准（「川娃子 双椒酱」应记为
                # 品牌命中而非"双椒酱"这个词）。
                for brand in rule["brands_exclusive"]:
                    if brand in text:
                        return rule["category"], f"品牌·{brand}"
                for kw in rule["keywords"]:
                    if kw in text:
                        return rule["category"], kw
        return None

    def classify(self, title: str, body: str = "", price: str = "") -> Verdict:
        title = (title or "").strip()
        body = (body or "").strip()

        # 零价格优先判定：这类帖子多为虚拟活动或返红包凑单，
        # 与商品品类无关，故放在白名单之前（婴幼儿用品也不例外——
        # 0 元的"送"本质是活动，不是商品推荐）。
        if is_zero_price(price):
            return Verdict(drop=True, category="零价格活动",
                           matched=price.strip(),
                           reason=f"零价格活动｜{price.strip()}")

        kept = self._check_keep(title, body)
        if kept:
            return Verdict(drop=False, kept_by=kept, reason=f"例外保护：{kept}")

        hit = self._check_drop(title, body)
        if hit:
            cat, kw = hit
            return Verdict(drop=True, category=cat, matched=kw, reason=f"{cat}｜{kw}")

        return Verdict(drop=False, reason="不在排除清单")

    def evaluate(self, items: Iterable[dict]) -> dict:
        """批量评估，返回统计 + 明细。item 需含 title / body / price 字段。"""
        detail = []
        stats: dict[str, int] = {}
        kept_n = 0
        for it in items:
            v = self.classify(it.get("title", ""), it.get("body", ""),
                              it.get("price", ""))
            it = dict(it, verdict=v)
            detail.append(it)
            if v.drop:
                stats[v.category] = stats.get(v.category, 0) + 1
            else:
                kept_n += 1
        return {
            "total": len(detail),
            "kept": kept_n,
            "dropped": len(detail) - kept_n,
            "by_category": dict(sorted(stats.items(), key=lambda x: -x[1])),
            "detail": detail,
        }
